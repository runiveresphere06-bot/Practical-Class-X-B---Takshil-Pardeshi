# Program 16: Create a 2D array using NumPy

import numpy as np   # NumPy is the library for working with arrays

# A 2D array is a list of lists (rows and columns)
arr = np.array([[1, 2, 3],
                [4, 5, 6]])

print("2D Array:")
print(arr)
print("Shape (rows, columns):", arr.shape)
print("Number of dimensions:", arr.ndim)
